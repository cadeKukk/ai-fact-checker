export function findTerm(name: string): AITerm | undefined {
  const lower = name.toLowerCase()
  const exact = allTerms.find((t) => t.term.toLowerCase() === lower)
  if (exact) return exact
  const withoutParen = allTerms.find((t) => {
    const base = t.term.replace(/\s*\([^)]+\)/, '').trim().toLowerCase()
    return base === lower
  })
  if (withoutParen) return withoutParen
  const abbr = allTerms.find((t) => {
    const m = t.term.match(/\(([^)]+)\)/)
    return m && m[1].toLowerCase() === lower
  })
  return abbr
}
