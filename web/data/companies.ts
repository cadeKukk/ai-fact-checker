export function getAllSources(): Source[] {
  const seen = new Set<string>()
  const sources: Source[] = []

  for (const company of companies) {
    for (const source of company.sources) {
      if (!seen.has(source.url)) {
        seen.add(source.url)
        sources.push(source)
      }
    }
    for (const model of company.models) {
      for (const source of [
        ...model.sources,
        ...model.capabilities.flatMap((capability) => capability.sources ?? []),
        ...model.myths.flatMap((myth) => myth.source ? [myth.source] : []),
      ]) {
        if (!seen.has(source.url)) {
          seen.add(source.url)
          sources.push(source)
        }
      }
    }
  }

  for (const source of additionalSources) {
    if (!seen.has(source.url)) {
      seen.add(source.url)
      sources.push(source)
    }
  }

  // Citations attached to fact-check entries (e.g. the AI-detection studies)
  // should also show up in the central Sources view, deduped by URL.
  for (const qa of factCheckQAs) {
    for (const source of qa.sources) {
      if (!seen.has(source.url)) {
        seen.add(source.url)
        sources.push(source)
      }
    }
  }

  // Lesson citations use the same records and belong in the central index too.
  for (const lesson of [...lessons, ...advancedLessons]) {
    for (const section of lesson.sections) {
      for (const source of section.sources ?? []) {
        if (!seen.has(source.url)) {
          seen.add(source.url)
          sources.push(source)
        }
      }
    }
  }

  return sources
}

export function getCompanyForModel(modelId: string): AICompany | undefined {
  return companies.find((company) =>
    company.models.some((model) => model.id === modelId)
  )
}
